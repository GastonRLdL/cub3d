#include "../../inc/cub3D.h"

void	free_data(t_data *data)
{
	int	i;

	if (!data)
		return ;
	free(data->no);
	free(data->so);
	free(data->we);
	free(data->ea);
	if (data->map)
	{
		i = 0;
		while (data->map[i])
		{
			free(data->map[i]);
			i++;
		}
		free(data->map);
	}
}

void	free_split(char **arr)
{
	int	i;

	if (!arr)
		return ;
	i = 0;
	while (arr[i])
		free(arr[i++]);
	free(arr);
}
