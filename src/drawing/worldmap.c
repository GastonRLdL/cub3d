void	convert_od_to_1(char map[MAP_HEIGHT][MAP_WIDTH + 1])
{
	int	i;
	int	j;

	i = 0;
	while (i < MAP_HEIGHT)
	{
		j = 0;
		while (j < MAP_WIDTH)
		{
			if (map[i][j] == 'O' || map[i][j] == 'D')
			{
				map[i][j] = '1';
			}
			j++;
		}
		i++;
	}
}
